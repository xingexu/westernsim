// Usage: node tools/export_western_avatar.mjs /path/to/xingexuportfolio
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

if (process.argv.length !== 3) throw new Error("Pass the path to the portfolio checkout");
const portfolio = resolve(process.argv[2]);
const requirePortfolio = createRequire(resolve(portfolio, "package.json"));
const ts = requirePortfolio("typescript");
const modules = new Map();

function load(path) {
  if (modules.has(path)) return modules.get(path).exports;
  const module = { exports: {} };
  modules.set(path, module);
  const js = ts.transpileModule(readFileSync(path + ".ts", "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const require = (specifier) => {
    if (specifier.startsWith(".")) return load(resolve(dirname(path), specifier));
    if (specifier.startsWith("@/")) return load(resolve(portfolio, "src", specifier.slice(2)));
    return requirePortfolio(specifier);
  };
  new Function("require", "module", "exports", js)(require, module, module.exports);
  return module.exports;
}

const journey = (name) => load(resolve(portfolio, "src/lib/journey", name));
const { CHAPTERS } = journey("data");
const { buildAvatar, AVATAR_VOXEL_SIZE } = journey("avatar");
const { gridGeometry } = journey("mesh");
const { Grid } = journey("voxel");
const { ageTo, outfit } = CHAPTERS.find(({ id }) => id === "western");
const model = buildAvatar(ageTo, outfit);
const shoulderY = model.shoulder + 1;
const parts = [
  { name: "torso", pivot: [0, model.hip, 0], grid: model.torso },
  { name: "head", pivot: [0, shoulderY + 1, 0], grid: model.head },
  { name: "leftLeg", pivot: [0, model.hip, 0], grid: model.legL },
  { name: "rightLeg", pivot: [0, model.hip, 0], grid: model.legR },
];
for (const [label, side, grid] of [["left", -1, model.armL], ["right", 1, model.armR]]) {
  // Match the upper arm and elbow split in JourneyWorld.tsx.
  const upper = new Grid(), lower = new Grid();
  const hinge = Math.round(grid.bounds().minY / 2);
  grid.forEach((x, y, z, color) => {
    if (y >= hinge) upper.set(x, y, z, color);
    else lower.set(x, y - hinge, z, color);
  });
  const x = side * model.shoulderX;
  parts.push({ name: label + "Arm", pivot: [x, shoulderY, 0], grid: upper },
             { name: label + "Forearm", pivot: [0, hinge * AVATAR_VOXEL_SIZE, 0], grid: lower });
}

// Encode each exposed quad in its source winding, with four baked vertex colors.
// The vertices fit in half-unit coordinates. A corner is a three-bit offset.
function quads(grid) {
  const geometry = gridGeometry(grid, [0, 0, 0], 0.02, AVATAR_VOXEL_SIZE);
  const { position, color } = geometry.attributes;
  const rows = [];
  for (let first = 0; first < position.count; first += 4) {
    const pos = Array.from(position.array.slice(first * 3, (first + 4) * 3));
    const base = [0, 1, 2].map(axis => Math.min(pos[axis], pos[3 + axis], pos[6 + axis], pos[9 + axis]));
    const vertices = Array.from({ length: 4 }, (_, i) => {
      const offsets = base.map((low, axis) => (pos[i * 3 + axis] - low) / AVATAR_VOXEL_SIZE);
      if (offsets.some(v => v !== 0 && v !== 1)) throw new Error("Unexpected avatar geometry");
      return offsets[0] | offsets[1] << 1 | offsets[2] << 2;
    });
    const mask = vertices.reduce((sum, v, i) => sum | v << (3 * i), 0);
    const colors = Array.from({ length: 4 }, (_, i) => {
      const at = (first + i) * 3;
      return "0x" + Array.from(color.array.slice(at, at + 3), v =>
        Math.round(255 * Math.max(0, Math.min(v, 1))).toString(16).padStart(2, "0")).join("");
    });
    const origin = base.map(v => v / AVATAR_VOXEL_SIZE);
    rows.push(`    {${origin.join(", ")}, ${mask}, {${colors.join(", ")}}},`);
  }
  geometry.dispose();
  return rows.join("\n");
}

const commit = execFileSync("git", ["-C", portfolio, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
writeFileSync(new URL("../src/western_avatar_data.hpp", import.meta.url), `// Generated by tools/export_western_avatar.mjs from xingexu/xingexuportfolio@${commit}.
#pragma once
#include <cstdint>

namespace wsim::westernAvatar {

struct Quad {
    std::int8_t x, y, z;
    std::uint16_t corners;
    std::uint32_t colors[4];
};

inline constexpr float height = ${model.height + 1}.f;
inline constexpr float voxelSize = ${AVATAR_VOXEL_SIZE}f;

${parts.map(({ name, pivot, grid }) => `inline constexpr float ${name}Pivot[]{${pivot.join(", ")}};
inline constexpr Quad ${name}[]{
${quads(grid)}
};`).join("\n\n")}

} // namespace wsim::westernAvatar
`);

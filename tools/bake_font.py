"""Bake Pixelify Sans into the embedded ASCII atlas (requires Pillow)."""

import argparse
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def bake(font_path, output):
    size, cell, columns = 16, 24, 24
    atlas = Image.new("L", (cell * columns, cell * 8))
    draw = ImageDraw.Draw(atlas)
    advances = []
    draw.fontmode = "1"
    for weight, name in enumerate(("Regular", "Bold")):
        font = ImageFont.truetype(font_path, size)
        font.set_variation_by_name(name)
        for i in range(96):
            text = chr(32 + i) if i < 95 else "?"
            slot = weight * 96 + i
            x, y = (slot % columns) * cell, (slot // columns) * cell
            draw.text((x + 2, y + size), text, font=font, fill=255, anchor="ls")
            advances.append(round(font.getlength(text) * 32))

    compressed = []
    for value, pixels in groupby(atlas.getdata()):
        count = sum(1 for _ in pixels)
        while count:
            run = min(count, 255)
            compressed.extend((run, value))
            count -= run

    def rows(values, length):
        return "\n".join("    " + ", ".join(map(str, values[i : i + length])) + ","
                         for i in range(0, len(values), length))

    output.write_text(
        "// Generated by tools/bake_font.py from Pixelify Sans. See assets/PixelifySans-OFL.txt.\n"
        "#pragma once\n#include <cstdint>\n\nnamespace wsim::font {\n"
        f"inline constexpr int width = {atlas.width}, height = {atlas.height};\n"
        f"inline constexpr int cell = {cell}, columns = {columns}, size = {size};\n"
        f"inline constexpr std::uint16_t advances[] = {{\n{rows(advances, 16)}\n}};\n"
        f"inline constexpr std::uint8_t pixels[] = {{\n{rows(compressed, 24)}\n}};\n"
        "} // namespace wsim::font\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    bake(args.font, args.output)
